//! Minimal interface localisation for the desktop app.
//!
//! Phase one covers the core operating screen: the top bar, the drop area, the
//! main controls, and the key result labels. The Handbook prose in
//! `reference.rs` is still English and is translated separately, because it is
//! long and needs a native review before anyone relies on it.
//!
//! Every string is `&'static str`, so [`T`] is `Copy` and can be looked up at
//! each call site with no borrowing or allocation.

/// Interface languages the window can switch between at runtime.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Ru,
    My,
    La,
}

impl Lang {
    /// Short label for the language toggle.
    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "EN",
            Lang::Ru => "RU",
            Lang::My => "MY",
            Lang::La => "LA",
        }
    }
}

